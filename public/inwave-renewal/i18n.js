export let language = "ko";
try {
  const saved = localStorage.getItem("inwave-language");
  if (saved === "en") language = "en";
} catch {}
export const t = (key) =>
  translations[language][key] ?? translations.ko[key] ?? key;
export function applyLanguage(next = language) {
  language = next === "en" ? "en" : "ko";
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18n);
  });
  document
    .querySelectorAll("[data-i18n-label]")
    .forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nLabel)));
  document
    .querySelectorAll("[data-language]")
    .forEach((el) =>
      el.setAttribute("aria-pressed", String(el.dataset.language === language)),
    );
  try {
    localStorage.setItem("inwave-language", language);
  } catch {}
  document.title =
    "INWAVE — " +
    (language === "ko"
      ? "광고를 본 순간, 데이터가 시작됩니다."
      : "The moment an ad is seen, the data begins.");
  document.dispatchEvent(new CustomEvent("inwave:language"));
}
export function initLanguage() {
  document
    .querySelectorAll("[data-language]")
    .forEach((el) =>
      el.addEventListener("click", () => applyLanguage(el.dataset.language)),
    );
  applyLanguage();
}
